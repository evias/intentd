// Package mimegen generates a Go registry mapping MIME types to uint16 IDs
// from the jshttp/mime-db JSON dataset on Github.
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"sort"
	"strings"

	"golang.org/x/text/cases"
	"golang.org/x/text/language"
)

// caser converts segments to title case. Reuse one instance: it is safe for
// concurrent use and caches language-specific rules.
var caser = cases.Title(language.English)

// Entry mirrors the per-type object in mime-db's db.json.
type Entry struct {
	Source       string   `json:"source"`
	Compressible bool     `json:"compressible"`
	Extensions   []string `json:"extensions"`
	Charset      string   `json:"charset"`
}

// Load fetches or reads the mime-db JSON and returns the map of
// "type/subtype" -> Entry.
func Load(src string) (map[string]Entry, error) {
	var r io.Reader
	if src == "-" || src == "" {
		r = os.Stdin
	} else if strings.HasPrefix(src, "http://") || strings.HasPrefix(src, "https://") {
		resp, err := http.Get(src)
		if err != nil {
			return nil, fmt.Errorf("fetch %s: %w", src, err)
		}
		defer resp.Body.Close()
		if resp.StatusCode != http.StatusOK {
			return nil, fmt.Errorf("fetch %s: status %d", src, resp.StatusCode)
		}
		r = resp.Body
	} else {
		f, err := os.Open(src)
		if err != nil {
			return nil, err
		}
		defer f.Close()
		r = f
	}

	var db map[string]Entry
	if err := json.NewDecoder(r).Decode(&db); err != nil {
		return nil, fmt.Errorf("parse mime-db json: %w", err)
	}
	return db, nil
}

// Types returns the sorted list of MIME type names.
func Types(db map[string]Entry) []string {
	names := make([]string, 0, len(db))
	for name := range db {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// Render emits the Go source for the registry package.
// IDs start at 1 (0 is reserved as "unknown") and are assigned in
// alphabetical order for determinism.
func Render(pkg string, db map[string]Entry) ([]byte, error) {
	names := Types(db)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by github.com/evias/intentd. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Mime Types Source: github.com/jshttp/mime-db.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "import \"%s\"\n\n", "strings")
	fmt.Fprintf(&b, "// MimeTypeID is a compact, wire-safe identifier for a MIME type (fits uint16).\ntype MimeTypeID uint16\n\n")
	fmt.Fprintf(&b, "const (\n\tMimeTypeIDUnknown MimeTypeID = iota // 0 is reserved\n")

	constID := func(name string) string {
		parts := strings.Split(name, "/")
		if len(parts) != 2 {
			return ""
		}
		var sb strings.Builder
		for _, part := range parts {
			part = strings.ReplaceAll(part, "+", "Plus") // structured-syntax suffix: image/svg+xml
			part = strings.ReplaceAll(part, ".", "Dot")  // structured-syntax suffix: image/svg+xml.cap
			for _, seg := range strings.Split(part, "-") {
				switch strings.ToLower(seg) {
				case "svg":
					sb.WriteString("SVG")
				case "xml", "json":
					sb.WriteString(strings.ToUpper(seg))
				default:
					sb.WriteString(caser.String(strings.ToLower(seg)))
				}
			}
		}
		return sb.String()
	}

	for _, name := range names {
		if strings.ContainsAny(name, " \t") {
			continue // skip weird entries with spaces (e.g. "text/… with params")
		}
		id := constID(name)
		if id == "" {
			continue
		}
		fmt.Fprintf(&b, "\tMimeTypeID%s // %s\n", id, name)
	}
	b.WriteString(")\n\n")

	// byName / byID lookup tables
	fmt.Fprintf(&b, "var byName = map[string]MimeTypeID{\n")
	for _, name := range names {
		if strings.ContainsAny(name, " \t") {
			continue
		}
		id := constID(name)
		if id == "" {
			continue
		}
		fmt.Fprintf(&b, "\t%q: MimeTypeID%s,\n", name, id)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "var byID = map[MimeTypeID]string{\n")
	for _, name := range names {
		if strings.ContainsAny(name, " \t") {
			continue
		}
		id := constID(name)
		if id == "" {
			continue
		}
		fmt.Fprintf(&b, "\tMimeTypeID%s: %q,\n", id, name)
	}
	b.WriteString("}\n\n")

	b.WriteString(`// MimeTypeIDFromString resolves a full MIME type string (e.g. "image/png") to its MimeTypeID.
func MimeTypeIDFromString(ct string) (MimeTypeID, bool) {
	id, ok := byName[strings.ToLower(strings.TrimSpace(ct))]
	return id, ok
}

// String returns the MIME type string for a MimeTypeID, or "" if unknown.
func (id MimeTypeID) String() string {
	return byID[id]
}

// Valid reports whether the MimeTypeID is a known registry entry.
func (id MimeTypeID) Valid() bool {
	_, ok := byID[id]
	return ok
}
`)

	return []byte(b.String()), nil
}
